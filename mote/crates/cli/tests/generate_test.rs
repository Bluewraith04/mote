//! `@generate`: a trait names the Mote modifier that supplies it, and listing the trait runs the modifier.

use std::path::PathBuf;
use std::process::Command;

fn project(tag: &str, files: &[(&str, &str)]) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("mote_generate_{}_{}", tag, std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    for (name, text) in files {
        std::fs::write(dir.join(name), text).unwrap();
    }
    dir
}

fn mote(verb: &str, dir: &std::path::Path) -> (bool, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_mote")).arg(verb).arg(dir.join("main.mote")).output().unwrap();
    (out.status.success(), format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr)))
}

fn done(dir: PathBuf) {
    std::fs::remove_dir_all(dir).ok();
}

const LABELS: &str = "
import std.meta as meta

@modifier
pub fn label_modifier(d: meta.Decl) -> Result<meta.Additions, meta.Diagnostic> {
    if d.fields.len() > 0 {
        return Err(meta.Diagnostic.new(\"`\" + d.name + \"` has fields, and a label is for a type with none\"))
    }
    return Ok(meta.Additions.new(\"fn label(self) -> String { return \\\"\" + d.name + \"\\\" }\"))
}

@generate(label_modifier)
pub trait Labeled {
    fn label(self) -> String
}
";

#[test]
fn listing_display_or_debug_writes_the_methods() {
    let src = "import { Display, Debug } from std.traits\n\nclass P: (Display, Debug) {\n    x: Int\n}\n\nenum E: (Display) {\n    A\n}\n\nfn main() {\n    println(P { x: 2 }.to_string())\n    println(P { x: 2 }.debug())\n    println(E.A.to_string())\n}\n";
    let dir = project("list", &[("main.mote", src)]);
    let (ok, text) = mote("run", &dir);
    done(dir);
    assert!(ok && text.trim() == "P(x: 2)\nP { x: 2 }\nA", "{text}");
}

#[test]
fn listing_jsoncodec_and_args_writes_the_methods() {
    let src = "import { JsonCodec, to_text } from std.json\nimport { Args } from std.args\n\n@arg(n = count)\nstruct P: (JsonCodec, Args) {\n    /// how many\n    count: Int = 0\n}\n\nfn main() {\n    println(to_text(P { count: 2 }.to_json()).unwrap())\n    println(P.parse([\"prog\", \"-n\", \"5\"]).unwrap().count)\n}\n";
    let dir = project("codecs", &[("main.mote", src)]);
    let (ok, text) = mote("run", &dir);
    done(dir);
    assert!(ok && text.trim() == "{\"count\":2}\n5", "{text}");
}

#[test]
fn member_data_is_read_only_by_a_modifier_that_lists_it() {
    let reading = LABELS.replace("@modifier\n", "@modifier(reads = \"arg\")\n");
    let main = "import { Labeled } from .labels\n\n@arg(x = a)\nstruct Dog: (Labeled) {\n}\n\nfn main() {}\n";
    let dir = project("reads", &[("main.mote", main), ("labels.mote", &reading)]);
    let (_, text) = mote("check", &dir);
    done(dir);
    assert!(!text.contains("is not read by any trait"), "{text}");
    let dir = project("unread", &[("main.mote", main), ("labels.mote", LABELS)]);
    let (ok, text) = mote("check", &dir);
    done(dir);
    assert!(!ok && text.contains("`@arg` on a type is not read by any trait `Dog` lists"), "{text}");
}

#[test]
fn a_type_that_writes_the_method_keeps_it() {
    let src = "import { Display } from std.traits\n\nclass P: (Display) {\n    x: Int\n    fn to_string(self) -> String { return \"mine\" }\n}\n\nfn main() {\n    println(P { x: 2 }.to_string())\n}\n";
    let dir = project("written", &[("main.mote", src)]);
    let (ok, text) = mote("run", &dir);
    done(dir);
    assert!(ok && text.trim() == "mine", "{text}");
}

#[test]
fn expand_shows_what_a_listed_trait_wrote() {
    let src = "import { Display } from std.traits\n\nstruct P: (Display) {\n    x: Int\n}\n\nfn main() {}\n";
    let dir = project("expand", &[("main.mote", src)]);
    let (ok, text) = mote("expand", &dir);
    done(dir);
    assert!(ok && text.contains("// generated by Display (requested at line 3)") && text.contains("fn to_string(self) -> String"), "{text}");
}

#[test]
fn a_user_trait_names_a_modifier_in_its_own_module() {
    let main = "import { Labeled } from .labels\n\nstruct Dog: (Labeled) {\n}\n\nfn main() {\n    println(Dog {}.label())\n}\n";
    let dir = project("own", &[("main.mote", main), ("labels.mote", LABELS)]);
    let (ok, text) = mote("run", &dir);
    done(dir);
    assert!(ok && text.trim() == "Dog", "{text}");
}

#[test]
fn a_user_trait_names_a_modifier_by_path() {
    let modifier = LABELS.replace("@generate(label_modifier)\npub trait Labeled {\n    fn label(self) -> String\n}\n", "");
    let traits = "@generate(gen.label_modifier)\npub trait Labeled {\n    fn label(self) -> String\n}\n";
    let main = "import { Labeled } from .traits\n\nstruct Dog: (Labeled) {\n}\n\nfn main() {\n    println(Dog {}.label())\n}\n";
    let dir = project("path", &[("main.mote", main), ("traits.mote", traits), ("gen.mote", &modifier)]);
    let (ok, text) = mote("run", &dir);
    done(dir);
    assert!(ok && text.trim() == "Dog", "{text}");
}

#[test]
fn a_modifier_that_refuses_is_reported_where_the_trait_is_listed() {
    let main = "import { Labeled } from .labels\n\nstruct Dog: (Labeled) {\n    name: String\n}\n\nfn main() {}\n";
    let dir = project("refuse", &[("main.mote", main), ("labels.mote", LABELS)]);
    let (ok, text) = mote("check", &dir);
    done(dir);
    assert!(!ok && text.contains("listing `Labeled`: `Dog` has fields, and a label is for a type with none") && text.contains("main.mote:3"), "{text}");
}

#[test]
fn a_modifier_module_that_asks_for_a_modifier_is_refused() {
    let labels = LABELS.replace("import std.meta as meta\n", "import std.meta as meta\nimport { Display } from std.traits\n\nclass Inner: (Display) {\n    n: Int\n}\n");
    let main = "import { Labeled } from .labels\n\nstruct Dog: (Labeled) {\n}\n\nfn main() {}\n";
    let dir = project("separation", &[("main.mote", main), ("labels.mote", &labels)]);
    let (ok, text) = mote("check", &dir);
    done(dir);
    assert!(!ok && text.contains("a module a modifier uses cannot ask for `Display`"), "{text}");
}

#[test]
fn a_modifier_module_that_reaches_outside_is_refused() {
    let labels = LABELS.replace("import std.meta as meta\n", "import std.meta as meta\nimport std.fs\n");
    let main = "import { Labeled } from .labels\n\nstruct Dog: (Labeled) {\n}\n\nfn main() {}\n";
    let dir = project("impure", &[("main.mote", main), ("labels.mote", &labels)]);
    let (ok, text) = mote("check", &dir);
    done(dir);
    assert!(!ok && text.contains("a modifier cannot use `std.fs`"), "{text}");
}

#[test]
fn a_module_that_holds_a_modifier_cannot_define_main() {
    let both = format!("{LABELS}\nstruct Dog: (Labeled) {{\n}}\n\nfn main() {{\n    println(\"x\")\n}}\n");
    let dir = project("main", &[("main.mote", &both)]);
    let (ok, text) = mote("check", &dir);
    done(dir);
    assert!(!ok && text.contains("defines `main`; move the modifier to a module without one"), "{text}");
}

#[test]
fn two_traits_with_one_name_and_a_modifier_are_ambiguous() {
    let other = LABELS.replace("label_modifier", "other_modifier");
    let main = "import .labels\nimport .other\nimport { Labeled } from .labels\n\nstruct Dog: (Labeled) {\n}\n\nfn main() {}\n";
    let dir = project("ambiguous", &[("main.mote", main), ("labels.mote", LABELS), ("other.mote", &other)]);
    let (ok, text) = mote("check", &dir);
    done(dir);
    assert!(!ok && text.contains("`Labeled` names more than one trait with a modifier here"), "{text}");
}

#[test]
fn an_answer_is_kept_in_the_cache_and_used_again() {
    let src = "import { Display } from std.traits\n\nstruct P: (Display) {\n    x: Int\n}\n\nfn main() {}\n";
    let dir = project("cache", &[("main.mote", src)]);
    let build = dir.join(".build");
    let expand = || modules::MultiFileCompiler::new(dir.clone()).with_cache(build.clone()).expanded_sources(&dir.join("main.mote")).unwrap();
    let first = expand();
    assert!(first[0].1.contains("return \"P(x: ${self.x})\""), "{}", first[0].1);
    let entries: Vec<PathBuf> = walk(&build.join("stage0"));
    assert_eq!(entries.len(), 1, "{entries:?}");
    let text = std::fs::read_to_string(&entries[0]).unwrap();
    std::fs::write(&entries[0], text.replace("P(x:", "Cached(x:")).unwrap();
    let second = expand();
    done(dir);
    assert!(second[0].1.contains("return \"Cached(x: ${self.x})\""), "{}", second[0].1);
}

fn walk(dir: &std::path::Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    for entry in std::fs::read_dir(dir).into_iter().flatten().flatten() {
        let path = entry.path();
        if path.is_dir() {
            out.extend(walk(&path));
        } else {
            out.push(path);
        }
    }
    out
}
