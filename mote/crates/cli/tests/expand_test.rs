//! `mote expand` prints a program with the code its modifiers generate written into the declarations.

use std::process::Command;

fn expand(source: &str, tag: &str) -> (bool, String) {
    let dir = std::env::temp_dir().join(format!("mote_expand_{}_{}", tag, std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("main.mote"), source).unwrap();
    let out = Command::new(env!("CARGO_BIN_EXE_mote")).arg("expand").arg(dir.join("main.mote")).output().unwrap();
    std::fs::remove_dir_all(&dir).ok();
    (out.status.success(), format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr)))
}

#[test]
fn the_generated_methods_appear_inside_the_type() {
    let (ok, text) = expand("import { Display } from std.traits\n\nstruct P: (Display) {\n    x: Int\n}\n\nfn main() {}\n", "display");
    assert!(ok, "{text}");
    let generated = text.find("// generated by Display (requested at line 3)").expect("a generated block");
    assert!(text.find("struct P").unwrap() < generated && generated < text.find("fn main").unwrap(), "{text}");
    assert!(text.contains("fn to_string(self) -> String { return \"P(x: ${self.x})\" }"), "{text}");
}

#[test]
fn a_json_codec_shows_the_alias_its_code_uses() {
    let (ok, text) = expand("import { JsonCodec } from std.json\n\nstruct P: (JsonCodec) {\n    x: Int\n}\n\nfn main() {}\n", "json");
    assert!(ok, "{text}");
    assert!(text.contains("fn to_json(self) -> __m_json.Json"), "{text}");
}

#[test]
fn a_program_without_modifiers_says_so() {
    let (ok, text) = expand("fn main() {}\n", "none");
    assert!(ok && text.trim() == "No modifiers are applied.", "{text}");
}

#[test]
fn an_error_in_the_request_is_reported_like_any_other() {
    let (ok, text) = expand("@derive(Display)\nstruct P {\n    x: Int\n}\n", "bad");
    assert!(!ok && text.contains("there is no `@derive`: list the trait, `struct P: (Display)`"), "{text}");
}
