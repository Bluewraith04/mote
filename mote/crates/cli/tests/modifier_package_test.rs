//! A package defines a trait and its modifier; another package lists the trait and gets the methods.

use std::path::{Path, PathBuf};
use std::process::Command;

const FIXTURE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/programs_mote/same_package");

fn copy_dir(from: &Path, to: &Path) {
    std::fs::create_dir_all(to).unwrap();
    for entry in std::fs::read_dir(from).unwrap() {
        let entry = entry.unwrap();
        let target = to.join(entry.file_name());
        if entry.file_type().unwrap().is_dir() {
            copy_dir(&entry.path(), &target);
        } else {
            std::fs::copy(entry.path(), target).unwrap();
        }
    }
}

/// A workspace holding the `same` package and an `app` that depends on it by path.
fn workspace(tag: &str, main: &str) -> PathBuf {
    let root = std::env::temp_dir().join(format!("mote_modifier_pkg_{tag}_{}", std::process::id()));
    std::fs::remove_dir_all(&root).ok();
    copy_dir(Path::new(FIXTURE), &root.join("same"));
    let app = root.join("app");
    std::fs::create_dir_all(app.join("src")).unwrap();
    std::fs::write(app.join("mote.toml"), "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2026\"\nentry = \"src/main.mote\"\n\n[dependencies]\nsame = { path = \"../same\" }\n").unwrap();
    std::fs::write(app.join("src/main.mote"), main).unwrap();
    let (ok, text) = mote(&["sync"], &app);
    assert!(ok, "{text}");
    root
}

fn mote(args: &[&str], dir: &Path) -> (bool, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_mote")).args(args).current_dir(dir).output().unwrap();
    (out.status.success(), format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr)))
}

const APP: &str = "import { Same } from same\n\nstruct Point: (Same) {\n    x: Int\n    y: Int\n}\n\nclass Tag: (Same) {\n    name: String\n    var n: Int\n}\n\nfn main() {\n    println(Point { x: 1, y: 2 }.same(Point { x: 1, y: 2 }))\n    println(Point { x: 1, y: 2 }.same(Point { x: 1, y: 3 }))\n    println(Tag { name: \"a\", n: 1 }.same(Tag { name: \"a\", n: 1 }))\n}\n";

#[test]
fn the_package_tests_its_own_modifier() {
    let root = workspace("own", APP);
    let (ok, text) = mote(&["test"], &root.join("same"));
    std::fs::remove_dir_all(&root).ok();
    assert!(ok && text.contains("3 passed, 0 failed"), "{text}");
}

#[test]
fn another_package_lists_the_trait_and_runs_the_generated_methods() {
    let root = workspace("run", APP);
    let (ok, text) = mote(&["run"], &root.join("app"));
    std::fs::remove_dir_all(&root).ok();
    assert!(ok && text.trim() == "true\nfalse\ntrue", "{text}");
}

#[test]
fn expand_shows_the_methods_the_package_wrote() {
    let root = workspace("expand", APP);
    let (ok, text) = mote(&["expand"], &root.join("app"));
    std::fs::remove_dir_all(&root).ok();
    assert!(ok && text.contains("// generated by Same (requested at line 3)") && text.contains("return self.x == other.x && self.y == other.y"), "{text}");
}

#[test]
fn a_type_that_writes_same_keeps_its_own() {
    let main = "import { Same } from same\n\nstruct P: (Same) {\n    x: Int\n    fn same(self, other: Self) -> Bool { return true }\n}\n\nfn main() {\n    println(P { x: 1 }.same(P { x: 2 }))\n}\n";
    let root = workspace("own_method", main);
    let (ok, text) = mote(&["run"], &root.join("app"));
    std::fs::remove_dir_all(&root).ok();
    assert!(ok && text.trim() == "true", "{text}");
}

#[test]
fn the_modifier_refusing_is_reported_where_the_trait_is_listed() {
    let main = "import { Same } from same\n\nenum Color: (Same) {\n    Red\n}\n\nfn main() {}\n";
    let root = workspace("refuse", main);
    let (ok, text) = mote(&["check"], &root.join("app"));
    std::fs::remove_dir_all(&root).ok();
    assert!(!ok && text.contains("listing `Same`: `Color` is an enum") && text.contains("main.mote:3"), "{text}");
}
